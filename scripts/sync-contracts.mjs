#!/usr/bin/env node
// Copies the compiled DynamicBadge ABI into the web app and indexer as typed `as const` modules,
// so viem/wagmi infer function names, arguments and return types.
// Run after `forge build`: node scripts/sync-contracts.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const artifactPath = join(root, 'contracts/out/DynamicBadge.sol/DynamicBadge.json')

if (!existsSync(artifactPath)) {
  console.error('Missing build artifact. Run `forge build` in contracts/ first.')
  process.exit(1)
}

const { abi } = JSON.parse(readFileSync(artifactPath, 'utf8'))
const source = `// Generated by scripts/sync-contracts.mjs from contracts/out. Do not edit by hand.
export const badgeAbi = ${JSON.stringify(abi, null, 2)} as const
`

for (const target of ['web/src/lib/badge-abi.ts', 'indexer/src/badge-abi.ts']) {
  const file = join(root, target)
  if (!existsSync(dirname(dirname(file)))) continue
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, source)
  console.log(`wrote ${target} (${abi.length} entries)`)
}
